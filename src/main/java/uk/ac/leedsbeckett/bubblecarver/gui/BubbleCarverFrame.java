  private void loadArchive( Path selected, String title )
  {
    archive = new Archive( selected );
    try
    {
      jTabbedPane1.setSelectedIndex( 0 );
      archive.load();
      archive.loadTrees();
      this.setTitle( "Bubblecarver - " + title );
      this.manifestTree.setModel(archive.getManifestTreeModel()     );
      this.courseSettingsTree.setModel(archive.getCourseSettingsTreeModel()  );
      this.usersTree.setModel(archive.getUsersTreeModel()        );
      this.membershipTree.setModel(archive.getMembershipTreeModel()   );
      this.gradebookTree.setModel(archive.getGradebookTreeModel()    );
      int n=1;
      for ( TreeModel tm : archive.getAttemptFilesTreeModel() )
      {
        JScrollPane sp = new JScrollPane();
        JTree tree = new JTree();
        tree.setModel( tm );
        sp.getViewport().add( tree );
        this.attemptFilesTabbedPane.add( Integer.toString( n ), sp );
        n++;
      }
    }
    catch ( ArchiveException ex )
    {
      Logger.getLogger( BubbleCarverFrame.class.getName() ).log( Level.SEVERE, null, ex );
      JOptionPane.showMessageDialog( rootPane, "Something went wrong reading that archive: " + ex.getMessage() );
    }
  }
    
  private void openMenuItemActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_openMenuItemActionPerformed
  {//GEN-HEADEREND:event_openMenuItemActionPerformed
    
    JFileChooser chooser = new JFileChooser();
    chooser.setFileSelectionMode( JFileChooser.FILES_ONLY );
    int outcome = chooser.showOpenDialog( this );
    if ( outcome == JFileChooser.APPROVE_OPTION )
    {
      File selectedArchiveFile = chooser.getSelectedFile();
      if ( !selectedArchiveFile.exists() )
      {
        JOptionPane.showMessageDialog( rootPane, "Selected file doesn't exist." );
        return;            
      }
      if ( !selectedArchiveFile.isFile() )
      {
        JOptionPane.showMessageDialog( rootPane, "Selected file is not a regular file." );
        return;            
      }

      clear();

      Path root;
      Path p;
      try
      {
        zipfs = FileSystems.newFileSystem( selectedArchiveFile.toPath(), this.getClass().getClassLoader() );
        root = zipfs.getPath( "/" );
        p = root.resolve( "imsmanifest.xml" );
        if ( !Files.exists( p ) )
        {
          JOptionPane.showMessageDialog( rootPane, "Zip file is not a BBL course archive because there is no imsmanifest.xml file in it." );
          return;          
        }
      }
      catch ( Exception ex )
      {
        ex.printStackTrace();
        JOptionPane.showMessageDialog( rootPane, "Problem reading file - perhaps not a ZIP archive." );
        return;
      }

      loadArchive( root, selectedArchiveFile.getName() );
    }
    
  }//GEN-LAST:event_openMenuItemActionPerformed

  private void openResourceMenuItemActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_openResourceMenuItemActionPerformed
  {//GEN-HEADEREND:event_openResourceMenuItemActionPerformed
    
    if ( this.archive == null )
    {
      JOptionPane.showMessageDialog( rootPane, "No archive open." );
      return;                  
    }
    
    if ( this.selectedElement == null )
    {
      JOptionPane.showMessageDialog( rootPane, "No Selected resource in the manifest panel." );
      return;            
    }
    
    try
    {
      Resource resource = this.archive.findEntry( selectedElement );
      Document document = this.archive.loadXMLDocument( resource );
      TreeModel tm = this.archive.loadTreeModel( document );
      JScrollPane sp = new JScrollPane();
      JTree tree = new JTree();
      tree.setModel( tm );
      sp.getViewport().add( tree );
      this.otherResourcesTabbedPane.add( selectedElement.getAttribute( "xml:base" ), sp );
    }
    catch ( ArchiveException | IOException | SAXException ex )
    {
      Logger.getLogger( BubbleCarverFrame.class.getName() ).log( Level.SEVERE, null, ex );
    }
    
  }//GEN-LAST:event_openResourceMenuItemActionPerformed

  private void reportAllButtonActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_reportAllButtonActionPerformed
  {//GEN-HEADEREND:event_reportAllButtonActionPerformed
    if ( baseDir == null )
    {
      JOptionPane.showMessageDialog( rootPane, "Select an archive scan directory first." );
      return;
    }
    if ( !baseDir.exists() )
    {
      JOptionPane.showMessageDialog( rootPane, "Selected archive scan directory doesn't exist." );
      return;
    }
    if ( !baseDir.isDirectory() )
    {
      JOptionPane.showMessageDialog( rootPane, "Selected archive scan directory isn't a directory." );
      return;
    }
    if ( reportDir == null )
    {
      JOptionPane.showMessageDialog( rootPane, "Select a student report directory first." );
      return;
    }
    if ( !reportDir.exists() )
    {
      JOptionPane.showMessageDialog( rootPane, "Selected student report directory doesn't exist." );
      return;
    }
    if ( !reportDir.isDirectory() )
    {
      JOptionPane.showMessageDialog( rootPane, "Selected student report directory isn't a directory." );
      return;
    }

    batchProcessor = new BatchProcessor(
      config,
      this,
      baseDir.toPath(),
      reportDir.toPath(),
      extractCheckBox.isSelected(),
      reportCheckBox.isSelected(),
      digestCheckBox.isSelected() );
    Thread t = new Thread( batchProcessor );
    t.start();

  }//GEN-LAST:event_reportAllButtonActionPerformed

